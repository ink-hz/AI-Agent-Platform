@pytest.mark.postgres
def test_typed_producer_constraints_and_restricted_acl(voc_database):
    dsn, reader_dsn, _, _, actor_dsn = voc_database
    with psycopg.connect(actor_dsn, autocommit=True) as producer:
        with pytest.raises(psycopg.errors.UniqueViolation):
            producer.execute("insert into voc_core.outbox_messages (source_inbound_message_id,status,content,recipient_staff_id) values (1,'pending','duplicate',%s)", (UID,))
        with pytest.raises(psycopg.errors.ForeignKeyViolation):
            producer.execute("insert into voc_core.outbox_messages (source_inbound_message_id,status,content,recipient_staff_id) values (999,'pending','orphan',%s)", (UID,))
    with psycopg.connect(reader_dsn, autocommit=True) as reader:
        reader.execute('set default_transaction_read_only=off')
        for query in ('select recipient_staff_id from voc_core.outbox_messages',
                      'select * from public.unrelated_business',
                      "update voc_core.outbox_messages set status='sent'",
                      'delete from voc_core.outbox_messages',
                      "insert into voc_core.outbox_messages(status,content,recipient_staff_id) values ('sent','forbidden','" + UID + "')"):
            with pytest.raises(psycopg.errors.InsufficientPrivilege):
                reader.execute(query)
    with psycopg.connect(make_conninfo(dsn,user='voc_contract_employee')) as employee:
        employee.execute("select set_config('app.employee_id',%s,true)", (UID,))
        assert employee.execute('select count(*) from voc_core.outbox_messages').fetchone() == (2,)
        employee.execute("select set_config('app.employee_id',%s,true)", (str(uuid4()),))
        assert employee.execute('select count(*) from voc_core.outbox_messages').fetchone() == (0,)


@pytest.mark.postgres
def test_producer_reader_encrypted_consumer_and_visibility_failure_preserves_snapshot(voc_database):
    dsn, _, profile, _, actor_dsn = voc_database
    root = Path(__file__).parents[1]
    with psycopg.connect(dsn,autocommit=True) as owner:
        for migration in ('008_cloud_replica.sql','cloud_agent_sync/001_agent_sources.sql'):
            owner.execute((root / 'migrations' / migration).read_text())
        owner.execute('grant platform_cloud_sync to voc_contract_writer')
        owner.execute('grant platform_replica_read to voc_contract_reader')
        owner.execute("select platform_replica.set_agent_publisher('voc','voc','cloud_direct','cloud','voc_contract_writer','voc-contract')")
    clock = [NOW]
    cipher = FieldCipher(b'e' * 32)
    store = CloudSyncStore(make_conninfo(dsn,user='voc_contract_writer'),cipher=cipher)
    events = []
    worker = CloudSyncWorker(store=store,identity_key=b'k'*32,policy=SanitizationPolicy(),
        include_verified_subject=True,clock=lambda:clock[0],emit=events.append,
        source_factory=lambda p:DatabaseAgentSource(p,clock=lambda:clock[0]))
    repository = ReplicaObservabilityRepository(make_conninfo(dsn,user='voc_contract_reader'),cipher=cipher,now=lambda:clock[0])
    result = worker.run_once(profile)
    assert result is not None and result.source_turns == 2
    print('VOC source_elapsed_ms=' + str(events[-1]['source_elapsed_ms']))
    snapshot = DatabaseAgentSource(profile).read_snapshot()
    assert Counter(turn.outcome for session in snapshot.sessions for turn in session.turns) == {'sent':1,'delivery_pending':1}
    assert repository.usage_snapshot().records[0].total_conversations == 1
    with psycopg.connect(dsn,autocommit=True) as owner:
        owner.execute("update voc_core.outbox_messages set status='failed' where source_inbound_message_id=2")
    clock[0] += timedelta(seconds=10)
    assert worker.run_once(profile).source_turns == 2
    assert Counter(turn.outcome for session in DatabaseAgentSource(profile).read_snapshot().sessions for turn in session.turns) == {'sent':1,'delivery_failed':1}
    # A genuinely absent delivery remains unknown even when its job is done.
    with psycopg.connect(actor_dsn) as producer:
        producer.execute("insert into voc_raw.inbound_messages (id,sender_internal_user_id,conversation_id,conversation_type,received_at,text_content) values (3,%s,'conversation','group',%s,'no receipt')",(UID,NOW))
        producer.execute("insert into voc_raw.interaction_jobs values (3,'done')")
    clock[0] += timedelta(seconds=10)
    assert worker.run_once(profile).source_turns == 3
    outcomes = Counter(turn.outcome for session in DatabaseAgentSource(profile).read_snapshot().sessions for turn in session.turns)
    assert outcomes == {'sent':1,'delivery_failed':1,'unavailable':1}
    with psycopg.connect(dsn,autocommit=True) as owner:
        before = owner.execute('select session_key,display_payload,payload_nonce,payload_sha256 from platform_replica.sessions').fetchall()
        success = owner.execute("select last_source_success_at,last_published_at,source_sessions,source_turns from platform_replica.agent_sources where agent_id='voc'").fetchone()
        owner.execute(f'drop policy {POLICY} on voc_core.outbox_messages')
    clock[0] += timedelta(seconds=10)
    assert worker.run_once(profile) is None
    assert events[-1]['error_code'] == 'source_visibility_unverified'
    with psycopg.connect(dsn) as owner:
        assert owner.execute('select session_key,display_payload,payload_nonce,payload_sha256 from platform_replica.sessions').fetchall() == before
        assert owner.execute("select last_source_success_at,last_published_at,source_sessions,source_turns from platform_replica.agent_sources where agent_id='voc'").fetchone() == success
    state = store.source_statuses()['voc']
    assert state['last_error'] == 'source_visibility_unverified'
    assert not healthy_sources({'voc':state},(profile,),now=clock[0],max_age_seconds=60)
    assert repository.usage_snapshot().records[0].total_conversations == 1


@pytest.mark.postgres
def test_policy_contract_and_business_read_share_transaction_and_ddl_lock(voc_database):
    dsn, _, profile, _, _ = voc_database
    checked = []
    def factory(*args, **kwargs):
        real = psycopg.connect(*args,**kwargs)
        class Cursor:
            def __init__(self): self.cursor = real.cursor()
            def execute(self,query,params=None):
                self.cursor.execute(query,params)
                rendered = query.as_string(real) if hasattr(query,'as_string') else str(query)
                if 'from pg_policy where polrelid=' in rendered:
                    transaction = real.execute("select current_setting('transaction_isolation') as isolation,current_setting('transaction_read_only') as readonly").fetchone()
                    assert tuple(transaction.values()) == ('repeatable read','on')
                    with psycopg.connect(dsn,autocommit=True) as ddl:
                        ddl.execute("set lock_timeout='50ms'")
                        with pytest.raises(psycopg.errors.LockNotAvailable):
                            ddl.execute(f'drop policy {POLICY} on voc_core.outbox_messages')
                    checked.append(True)
                return self
            def __getattr__(self,name): return getattr(self.cursor,name)
        class Connection:
            def __enter__(self): real.__enter__(); return self
            def __exit__(self,*args): return real.__exit__(*args)
            def transaction(self): return real.transaction()
            def cursor(self): return Cursor()
        return Connection()
    assert DatabaseAgentSource(profile,connection_factory=factory).read_snapshot().complete
    assert checked == [True]


@pytest.mark.postgres
@pytest.mark.parametrize('policy_definition', [
    'for insert to platform_sync_voc_read with check (true)',
    'as restrictive for select to platform_sync_voc_read using (true)',
])
def test_installer_refuses_conflicting_owned_policy_without_touching_business_policy(voc_database, policy_definition):
    dsn, _, _, tool, _ = voc_database
    with psycopg.connect(dsn,autocommit=True) as owner:
        owner.execute(f'drop policy {POLICY} on voc_core.outbox_messages')
        owner.execute(f'create policy {POLICY} on voc_core.outbox_messages {policy_definition}')
        before = owner.execute('select polname,polcmd,polpermissive,polroles,pg_get_expr(polqual,polrelid),pg_get_expr(polwithcheck,polrelid) from pg_policy order by polname').fetchall()
        with pytest.raises(psycopg.errors.RaiseException,match='cloud_sync_source_policy_conflict'):
            owner.execute(tool.source_role_sql('voc','contract_password'))
        owner.execute('rollback')
        assert owner.execute('select polname,polcmd,polpermissive,polroles,pg_get_expr(polqual,polrelid),pg_get_expr(polwithcheck,polrelid) from pg_policy order by polname').fetchall() == before
