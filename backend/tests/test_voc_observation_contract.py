@pytest.mark.postgres
def test_provision_repairs_actual_insert_only_rls_and_is_idempotent(voc_database):
    dsn, reader_dsn, _, tool, _ = voc_database
    with psycopg.connect(dsn, autocommit=True) as owner:
        owner.execute(f'drop policy if exists {POLICY} on voc_core.outbox_messages')
    with psycopg.connect(reader_dsn) as reader:
        assert reader.execute('select count(id) from voc_raw.inbound_messages').fetchone() == (2,)
        assert reader.execute("select count(status) from voc_core.outbox_messages where status='sent'").fetchone() == (0,)
    with psycopg.connect(dsn, autocommit=True) as owner:
        before = owner.execute("select polname,pg_get_expr(polqual,polrelid),pg_get_expr(polwithcheck,polrelid) from pg_policy order by polname").fetchall()
        for _ in range(2):
            owner.execute(tool.source_role_sql('voc','contract_password'))
        after = owner.execute("select polname,pg_get_expr(polqual,polrelid),pg_get_expr(polwithcheck,polrelid) from pg_policy where polname<>%s order by polname", (POLICY,)).fetchall()
        assert after == before
        assert owner.execute("select has_table_privilege('voc_contract_employee','public.unrelated_business','SELECT')").fetchone() == (True,)
    with psycopg.connect(reader_dsn) as reader:
        assert reader.execute("select count(status) from voc_core.outbox_messages where status='sent'").fetchone() == (1,)
        assert reader.execute('select count(status) from voc_core.outbox_messages').fetchone() == (2,)


